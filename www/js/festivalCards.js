/* ============ 抽取函数（当天命中则随机返回一条，未命中返回 null） ============ */
function _monthDay(d) {
  return (d.getMonth() + 1) * 100 + d.getDate();
}
function _pickFestivalCard(date) {
  const md = _monthDay(date);
  // 1) 精确匹配固定日期节日
  for (const k in FESTIVAL_CARDS) {
    const f = FESTIVAL_CARDS[k];
    if (f.m * 100 + f.d === md) {
      return { type: 'festival', key: k, name: f.name, title: f.title, line: f.lines[Math.floor(Math.random() * f.lines.length)] };
    }
  }
  // 2) 节气：仅在当天精确命中（节气当天才显示节气动画签，其余日子不命中）
  for (const t of SOLAR_TERM_CARDS) {
    if (t.m * 100 + t.d === md) {
      return { type: 'solar', key: t.id, name: t.name, title: t.title, line: t.lines[Math.floor(Math.random() * t.lines.length)] };
    }
  }
  return null;
}
/* 当天节日/节气卡片（供入梦签调用）。同一天多次调用会返回不同句，属随机；如需当日固定，由调用方缓存。 */
function pickFestivalCard(date) {
  return _pickFestivalCard(date || new Date());
}
/* 字卡模式经期关心句（inPeriod=是否在经期中） */
function pickPeriodCareLine(inPeriod) {
  const pool = inPeriod ? PERIOD_CARE_LINES_IN : PERIOD_CARE_LINES_NEAR;
  return pool[Math.floor(Math.random() * pool.length)];
}
